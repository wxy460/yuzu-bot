def register_campus_leisure(router, catalog, song_card):
    @router.command("塔罗牌", "抽一张塔罗牌，读正位或逆位的牌意", category="占卜与闲聊")
    @router.command("塔罗牌3", "抽三张牌，查看过去、现在与未来的线索", category="占卜与闲聊")
    async def tarot(req):
        three = req.command == "塔罗牌3"
        positions = ("过去", "现在", "未来") if three else ("今日一张",)
        rows = []
        for position, (name, upright, reversed_) in zip(
            positions, random.sample(DECK, len(positions))
        ):
            is_reversed = random.choice((False, True))
            face = "逆位" if is_reversed else "正位"
            reading = reversed_ if is_reversed else upright
            rows.append((position, f"{name} · {face}\n{reading}"))
        return await academy_card(
            "柚子的三张牌阵" if three else "柚子的塔罗手记", rows, section="占卜与闲聊"
        )

    @router.command(
        "推歌",
        "随机推荐舞萌曲目，也可按曲名、别名、艺人或 ID 点歌",
        aliases=("点歌",),
        usage="/推歌 [关键词] 或 /点歌 曲名",
        category="占卜与闲聊",
    )
    async def request_song(req):
        keyword = req.argument.strip()
        try:
            if keyword:
                exact = await catalog.resolve(keyword)
                if exact:
                    return await song_card(exact, "柚子的点歌单")
                songs = await catalog.search(keyword)
                if not songs:
                    return "没有找到匹配的舞萌曲目。可以试试艺人名、常用别名或歌曲 ID。"
            else:
                songs = await catalog.songs()
                if not songs:
                    return "舞萌曲库暂时为空，请稍后再试。"
        except SongCatalogError as exc:
            return str(exc)
        return await song_card(random.choice(songs), "柚子的点歌单")
